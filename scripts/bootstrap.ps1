# Sets up the Brokspace polyrepo for local development (Windows).
#
# Siblings are cloned next to this repository, and ..\.cargo\config.toml makes
# every repository build against the local brok-sdk checkout instead of the
# crates.io release.
$ErrorActionPreference = 'Stop'

$OrgUrl = if ($env:BROK_ORG_URL) { $env:BROK_ORG_URL } else { 'https://github.com/brokspace' }
$Repos = @('brok-sdk', 'brok-agent', 'brok-shard-template')

$Here = Split-Path -Parent $PSScriptRoot
$Parent = Split-Path -Parent $Here

foreach ($Repo in $Repos) {
    $Target = Join-Path $Parent $Repo
    if (Test-Path $Target) {
        Write-Host "- $Repo already present"
    } else {
        Write-Host "- cloning $Repo"
        git clone "$OrgUrl/$Repo.git" $Target
        if ($LASTEXITCODE -ne 0) { throw "git clone $Repo failed" }
    }
}

$CargoDir = Join-Path $Parent '.cargo'
New-Item -ItemType Directory -Force $CargoDir | Out-Null
$Config = @'
# Polyrepo development: build every Brokspace repository in this folder
# against the sibling `brok-sdk` checkout instead of the crates.io release.
# Generated by brok/scripts/bootstrap.(sh|ps1); not part of any repository.
[patch.crates-io]
brok-sdk = { path = "brok-sdk" }
'@
Set-Content -Path (Join-Path $CargoDir 'config.toml') -Value $Config -Encoding utf8
Write-Host "OK: wrote $CargoDir\config.toml"
Write-Host ""
Write-Host "Next: cd brok; cargo test   (or: cargo test --no-default-features)"
