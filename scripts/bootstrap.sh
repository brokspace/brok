#!/usr/bin/env bash
# Sets up the Brokspace polyrepo for local development.
#
# Run from anywhere: siblings are cloned next to this repository, and
# ../.cargo/config.toml makes every repository build against the local
# brok-sdk checkout instead of the crates.io release.
set -euo pipefail

ORG_URL="${BROK_ORG_URL:-https://github.com/brokspace}"
REPOS=(brok-sdk brok-agent brok-shard-template)

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
parent="$(dirname "$here")"

for repo in "${REPOS[@]}"; do
  if [ -d "$parent/$repo/.git" ] || [ -d "$parent/$repo" ]; then
    echo "• $repo already present"
  else
    echo "• cloning $repo"
    git clone "$ORG_URL/$repo.git" "$parent/$repo"
  fi
done

mkdir -p "$parent/.cargo"
cat > "$parent/.cargo/config.toml" <<'EOF'
# Polyrepo development: build every Brokspace repository in this folder
# against the sibling `brok-sdk` checkout instead of the crates.io release.
# Generated by brok/scripts/bootstrap.(sh|ps1); not part of any repository.
[patch.crates-io]
brok-sdk = { path = "brok-sdk" }
EOF
echo "✓ wrote $parent/.cargo/config.toml"
echo
echo "Next: cd brok && cargo test   (or: cargo test --no-default-features)"
